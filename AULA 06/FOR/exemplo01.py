
# Se precisarmo de fazer isso dez vezes?
for i in range(10):
    numero = int(input('Digite um número: '))
    dobro = numero * 2
    triplo = numero * 3
    quadrado = numero ** 2

    print(f'O dobro de {numero} é {dobro}')
    print(f'O triplo de {numero} é {triplo}')
    print(f'O quadrado de {numero} é {quadrado}')
