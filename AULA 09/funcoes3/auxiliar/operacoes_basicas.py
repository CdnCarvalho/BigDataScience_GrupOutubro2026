# Funções para operações básicas - Atividade03
# função para somar
def calcula_somar(a, b):
  soma = a + b
  return soma


# função para subtrair
def calcula_subtrair(a, b):
  subtracao = a - b
  return subtracao


# função para multiplicar
def calcula_multiplicar(a, b):
  multiplicacao = a * b
  return multiplicacao


# função para dividir
def calcula_dividir(a, b):
  divisao = a / b
  return divisao
